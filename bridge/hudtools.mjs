/**
 * Turns the four in-process HUD servers into opencode custom tools.
 *
 * The brain is now `opencode run`, which will not touch our HUD unless it knows
 * about it. opencode's own config file is off-limits to us — on Windows the Zen
 * free tier the brain runs on is only served when the config is exactly the
 * default — but its custom-tools directory is not part of that check (verified
 * against a live bridge). So the HUD servers ship as plain `.opencode/tools/*.js`
 * files, generated here at boot from the same modules the bridge uses in
 * process; when opencode calls one of them it POSTs the arguments back to the
 * bridge, which runs the real handler over its live WebSocket.
 */

import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { displayServer } from './panels.mjs'
import { uiServer } from './ui.mjs'
import { chromeServer } from './chrome.mjs'
import { visionServer } from './vision.mjs'
import { weatherServer } from './weather.mjs'
import { preferencesServer } from './preferences.mjs'
import { notificationsServer } from './notifications.mjs'
import { gmailServer } from './gmail.mjs'
import { calendarServer } from './calendar.mjs'
import { systemsServer } from './systems.mjs'
import { memoryServer } from './memory.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))

/** Dummy closures are enough here — we only read the tool descriptors. */
const noop = () => {}

const SOURCES = [
  ['jarvis', () => displayServer(noop, noop)],
  ['jarvis_ui', () => uiServer(noop)],
  ['jarvis_chrome', () => chromeServer({ allowWrites: true })],
  ['jarvis_eyes', () => visionServer(noop)],
  ['jarvis_weather', () => weatherServer()],
  ['jarvis_prefs', () => preferencesServer()],
  ['jarvis_notify', () => notificationsServer()],
  ['jarvis_gmail', () => gmailServer()],
  ['jarvis_calendar', () => calendarServer()],
  ['jarvis_memory', () => memoryServer()],
  ['jarvis_systems', () => systemsServer(() => ({}))],
]

/** Server keys -> tool descriptor arrays. Built once, shares no mutable state. */
export const HUD_SERVERS = (() => {
  const map = {}
  for (const [key, build] of SOURCES) {
    const server = runSafely(build)
    map[key] = server ? server.tools : []
  }
  return map
})()

function runSafely(build) {
  try {
    return build()
  } catch (err) {
    console.warn('[jarvis] could not build HUD server:', err?.message ?? err)
    return null
  }
}

/**
 * Write the tool files into <configDir>/tools so a docs-compatible opencode
 * picks them up. Also returns every descriptor, keyed by tool name.
 */
export function writeHudTools(configDir, bridgeUrl) {
  const toolsDir = join(configDir, 'tools')
  mkdirSync(toolsDir, { recursive: true })

  const all = []
  for (const server of Object.values(HUD_SERVERS)) {
    for (const t of server) {
      all.push(t)
    }
  }

  for (const t of all) {
    // The filename becomes the tool name, so one tool per file, default export.
    // `args` MUST be a per-field map (open-code custom-tools format), never a
    // JSON-Schema `{ type: 'object', properties, required }` object — open-code
    // treats the top level as field definitions and silently mangles real
    // arguments into `{ properties: {...} }`.
    const fields = Object.entries(t.inputSchema?.properties ?? {}).map(([k, v]) => {
      const desc = v?.description ? `, description: ${JSON.stringify(v.description)}` : ''
      const enums = Array.isArray(v?.enum) ? `, enum: ${JSON.stringify(v.enum)}` : ''
      return `    ${JSON.stringify(k)}: { type: ${JSON.stringify(v?.type ?? 'string')}${desc}${enums} },`
    })
    const body =
      `// Generated by bridge/hudtools.mjs — do not edit.\n` +
      `export default {\n` +
      `  description: ${JSON.stringify(t.description)},\n` +
      `  args: {\n${fields.join('\n')}\n  },\n` +
      `  async execute(args) {\n` +
      `    const res = await fetch(${JSON.stringify(bridgeUrl)} + '/rpc/hud', {\n` +
      `      method: 'POST',\n` +
      `      headers: { 'content-type': 'application/json' },\n` +
      `      body: JSON.stringify({ token: process.env.JARVIS_HUD_TOKEN, tool: ${JSON.stringify(t.name)}, arguments: args }),\n` +
      `    })\n` +
      `    if (!res.ok) return 'HUD unavailable (HTTP ' + res.status + '). One plain sentence saying so.'\n` +
      `    return res.text()\n` +
      `  },\n` +
      `}\n`
    writeFileSync(join(toolsDir, `${t.name}.js`), body)
  }

  return all
}

/** Human-readable server list for the boot banner and the `ready` message. */
export function hudServerNames() {
  return Object.keys(HUD_SERVERS)
}

/** Where generated config (tools, prompt) lives. Not served, not git-tracked. */
export const HUD_RUNTIME_DIR = resolve(join(HERE, '.oc'))